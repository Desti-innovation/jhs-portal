"use server"

import { revalidatePath } from "next/cache"
import { redirect } from "next/navigation"
import { requireRole } from "@/lib/auth"
import { sql } from "@/lib/db"

export async function createStudentAction(
  prevState: { error?: string } | null,
  formData: FormData
) {
  await requireRole("hod", "admin")

  const first_name = String(formData.get("first_name") ?? "").trim()
  const last_name = String(formData.get("last_name") ?? "").trim()
  const middle_name = String(formData.get("middle_name") ?? "").trim() || null
  const other_name = String(formData.get("other_name") ?? "").trim() || null
  const gender = String(formData.get("gender") ?? "") || null
  const date_of_birth = String(formData.get("date_of_birth") ?? "") || null
  
  const father_name = String(formData.get("father_name") ?? "").trim() || null
  const father_phone = String(formData.get("father_phone") ?? "").trim() || null
  const mother_name = String(formData.get("mother_name") ?? "").trim() || null
  const mother_phone = String(formData.get("mother_phone") ?? "").trim() || null

  if (!first_name || !last_name) {
    return { error: "First and Last name are required" }
  }

  if (!father_phone && !mother_phone) {
    return { error: "At least one parent phone number is required for login." }
  }

  // Handle the image upload (convert to Base64 for now)
  let image_url = null
  const file = formData.get("image") as File | null
  if (file && file.size > 0) {
    const arrayBuffer = await file.arrayBuffer()
    const buffer = Buffer.from(arrayBuffer)
    image_url = `data:${file.type};base64,${buffer.toString("base64")}`
  }

  try {
    // The index_number is automatically generated by the SQL trigger we created earlier!
    await sql`
      INSERT INTO students (
        first_name, last_name, middle_name, other_name, 
        gender, date_of_birth, 
        father_name, father_phone, 
        mother_name, mother_phone, 
        image_url
      ) VALUES (
        ${first_name}, ${last_name}, ${middle_name}, ${other_name},
        ${gender}, ${date_of_birth},
        ${father_name}, ${father_phone},
        ${mother_name}, ${mother_phone},
        ${image_url}
      )
    `
  } catch (error) {
    return { error: "Failed to save student. Database error." }
  }

  revalidatePath("/dashboard/students")
  redirect("/dashboard/students")
}
export async function updateStudentAction(
  id: string,
  prevState: { error?: string } | null,
  formData: FormData
) {
  await requireRole("hod", "admin")

  const first_name = String(formData.get("first_name") ?? "").trim()
  const last_name = String(formData.get("last_name") ?? "").trim()
  const middle_name = String(formData.get("middle_name") ?? "").trim() || null
  const other_name = String(formData.get("other_name") ?? "").trim() || null
  const gender = String(formData.get("gender") ?? "") || null
  const date_of_birth = String(formData.get("date_of_birth") ?? "") || null
  
  const father_name = String(formData.get("father_name") ?? "").trim() || null
  const father_phone = String(formData.get("father_phone") ?? "").trim() || null
  const mother_name = String(formData.get("mother_name") ?? "").trim() || null
  const mother_phone = String(formData.get("mother_phone") ?? "").trim() || null

  if (!first_name || !last_name) {
    return { error: "First and Last name are required" }
  }

  if (!father_phone && !mother_phone) {
    return { error: "At least one parent phone number is required." }
  }

  // Check if a new image was uploaded
  let image_url = formData.get("existing_image") as string | null
  const file = formData.get("image") as File | null
  if (file && file.size > 0) {
    const arrayBuffer = await file.arrayBuffer()
    const buffer = Buffer.from(arrayBuffer)
    image_url = `data:${file.type};base64,${buffer.toString("base64")}`
  }

  try {
    await sql`
      UPDATE students SET
        first_name = ${first_name},
        last_name = ${last_name},
        middle_name = ${middle_name},
        other_name = ${other_name},
        gender = ${gender},
        date_of_birth = ${date_of_birth},
        father_name = ${father_name},
        father_phone = ${father_phone},
        mother_name = ${mother_name},
        mother_phone = ${mother_phone},
        image_url = ${image_url},
        updated_at = now()
      WHERE id = ${id}
    `
  } catch (error) {
    return { error: "Failed to update student." }
  }

  revalidatePath("/dashboard/students")
  redirect("/dashboard/students")
}